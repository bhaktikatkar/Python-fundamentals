# Day 7 - Tuples

# 1. Creating a tuple
numbers = (10, 20, 30, 40, 50)
print(numbers)

#--------------------------------------------------------------------------------------------
# 2. Tuple with different data types
student = ("Bhakti", 22, "Robotics & AI")
print(student)

#_-------------------------------------------------------------------------------------------
# 3. Indexing
print(numbers[0])
print(numbers[-1])

#--------------------------------------------------------------------------------------------
# 4. Slicing
print(numbers[1:4])

#--------------------------------------------------------------------------------------------
# 5. Length
print(len(numbers))

#--------------------------------------------------------------------------------------------
# 6. Checking membership
print(30 in numbers)

#----------------------------------------------------------------------------------------------
# 7. Tuple methods
values = (10, 20, 10, 30, 10)

print(values.count(10))
print(values.index(30))

#-----------------------------------------------------------------------------------------------
# 8. Nested tuple
students = (("A", 20), ("B", 21), ("C", 22))
print(students)

#-------------------------------------------------------------------------------------------
# 9. Loop through a tuple
for number in numbers:
    print(number)

#--------------------------------------------------------------------------------------------
# 10. Tuple unpacking
name, age, branch = student

print(name)
print(age)
print(branch)